// gen_opcodes.go writes opcodes.go, the table of the BEAM's opcodes, from
// lib/compiler/src/genop.tab of Erlang/OTP. "make generate" fetches the file of
// the pinned release and runs this:
//
//	go run ./internal/beam/gen_opcodes.go -tab build/genop.tab -tag OTP-27.3.4.1 -o internal/beam/opcodes.go
//
// A line of genop.tab that defines an opcode reads "N: name/arity", with a "-"
// before the name of an obsolete one. Nothing else of the file is read; its
// comments stay where they are.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var lineRE = regexp.MustCompile(`^(\d+):\s*(-?)([a-z][a-z_0-9]*)/(\d+)\s*$`)

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen_opcodes: ")
	tab := flag.String("tab", "genop.tab", "the genop.tab to read")
	tag := flag.String("tag", "", "the Erlang/OTP tag the table comes from")
	out := flag.String("o", "opcodes.go", "the Go file to write")
	flag.Parse()
	if *tag == "" {
		log.Fatal("-tag names the Erlang/OTP release the table comes from")
	}

	f, err := os.Open(*tab)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	type op struct {
		n        int
		name     string
		arity    int
		obsolete bool
	}
	var ops []op
	seen := map[int]bool{}
	max := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := lineRE.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		n, _ := strconv.Atoi(m[1])
		a, _ := strconv.Atoi(m[4])
		if seen[n] || n < 1 || n > 255 {
			log.Fatalf("opcode %d: duplicate or out of range", n)
		}
		seen[n] = true
		ops = append(ops, op{n, m[3], a, m[2] == "-"})
		if n > max {
			max = n
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(ops) == 0 {
		log.Fatalf("%s: no opcode found", *tab)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen_opcodes.go from genop.tab of Erlang/OTP %s. DO NOT EDIT.\n\n", *tag)
	b.WriteString("package beam\n\n")
	fmt.Fprintf(&b, "// GenopTag names the Erlang/OTP release whose genop.tab the opcode table was\n// generated from.\nconst GenopTag = %q\n\n", *tag)
	fmt.Fprintf(&b, "// MaxOpcode is the highest opcode number of the table.\nconst MaxOpcode = %d\n\n", max)
	b.WriteString("// The opcodes, by name. An obsolete one is kept, so that it can be named in a\n// message; no compiler of this century emits it.\nconst (\n")
	for _, o := range ops {
		obs := ""
		if o.obsolete {
			obs = ", obsolete"
		}
		fmt.Fprintf(&b, "\tOp%s Opcode = %d // %s/%d%s\n", camel(o.name), o.n, o.name, o.arity, obs)
	}
	b.WriteString(")\n\n")
	b.WriteString("var opcodes = [...]opcodeInfo{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\t%d: {%q, %d, %v},\n", o.n, o.name, o.arity, o.obsolete)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%s: %d opcodes, the highest %d\n", *out, len(ops), max)
}

// camel turns is_eq_exact into IsEqExact.
func camel(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}
