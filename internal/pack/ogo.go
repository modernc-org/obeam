package pack

import (
	"fmt"
	"io"
	"strconv"
	"strings"
)

// WriteOgo writes the image as the OctoGo package image, which the board
// program compiles in: constants and arrays, nothing to decode.
func (img *Image) WriteOgo(w io.Writer) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by obeam pack from %s. DO NOT EDIT.\n\n", strings.Join(img.Modules, ", "))
	b.WriteString("// Package image is the image obeam pack wrote: the modules' code with every\n// operand resolved, their atoms, their literals laid out as the board's terms,\n// and the tables of functions, funs and lines. DESIGN.md section 4 says what\n// each is.\n\n")
	fmt.Fprintf(&b, "// Entry is the code offset of EntryName, the function the image begins at,\n// and TableID the fingerprint of the VM's tables the image was packed for.\nconst (\n\tEntry     = %d\n\tEntryName = %q\n\tTableID   = 0x%08x\n)\n\n", img.Entry, img.EntryMFA, TableID())
	writeStrings(&b, "Atoms", "the atoms, by index", img.Atoms)
	writeLongs(&b, "Code", "the instruction stream; Code[0] is halt", img.Code, 8)
	writeLongs(&b, "Literals", "the literal heap, the arena's first longs", img.Literals, 8)
	writeLongs(&b, "Funcs", "the functions, by code offset: offset, module, function, arity with bit 8 for an export", img.Funcs, 4)
	writeLongs(&b, "Funs", "the funs, by make_fun3's index: code offset, arity, free variables", img.Funs, 3)
	writeLongs(&b, "Lines", "the lines, by code offset: offset, file, line", img.Lines, 3)
	writeStrings(&b, "Files", "the files Lines name", img.Files)
	writeLongs(&b, "Structs", "Elixir's structs: a module, and its fields in their order, a list", img.Structs, 2)
	src, err := FormatOgo(b.String())
	if err != nil {
		return err
	}
	_, err = io.WriteString(w, src)
	return err
}

func writeStrings(b *strings.Builder, name, doc string, ss []string) {
	fmt.Fprintf(b, "// %s is %s.\nvar %s = [%d]string{", name, doc, name, len(ss))
	for i, s := range ss {
		if i%6 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteByte(' ')
		}
		b.WriteString(strconv.Quote(s))
		b.WriteByte(',')
	}
	if len(ss) > 0 {
		b.WriteByte('\n')
	}
	b.WriteString("}\n\n")
}

func writeLongs(b *strings.Builder, name, doc string, ws []uint32, perLine int) {
	fmt.Fprintf(b, "// %s is %s.\nvar %s = [%d]uint32{", name, doc, name, len(ws))
	for i, w := range ws {
		if i%perLine == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteByte(' ')
		}
		fmt.Fprintf(b, "0x%x,", w)
	}
	if len(ws) > 0 {
		b.WriteByte('\n')
	}
	b.WriteString("}\n\n")
}
